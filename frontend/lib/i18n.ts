const DICTS: Record<Lang, Dict> = { ru, uz, en };

function typoDeep<T>(value: T, lang: Lang): T {
  if (typeof value === "string") return typo(value, lang) as T;
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, typoDeep(v, lang)])) as T;
  }
  return value;
}

const PREPARED: Partial<Record<Lang, Dict>> = {};

/** Словарь интерфейса; строки уже прошли типограф (неразрывные пробелы). */
export function getDict(lang: Lang): Dict {
  return (PREPARED[lang] ??= typoDeep(DICTS[lang] ?? ru, lang));
}

export function href(lang: Lang, path = ""): string {
  return `/${lang}${path}`;
}

export function telHref(phone: string): string {
  return `tel:${phone.replace(/[^\d+]/g, "")}`;
}
